"""Hugging Face automated export logic for LiteRT conversion.

This module provides the implementation for the 'hf' mode of the
`litert convert` command, orchestrating the download and conversion of
models directly from the Hugging Face Hub.
"""

from __future__ import annotations

import pathlib
import tempfile
from typing import Any

import click
from litert_cli.commands.convert import litert_lm_config

_DEFAULT_TARGET = "cpu_gpu"


def _export_hf():
  """Imports litert-torch lazily so `litert --help` does not load torch."""
  # pylint: disable=g-import-not-at-top
  from litert_torch.generative.export_hf import export

  return export


def _resolve_target(target: tuple[str, ...] | str | None) -> str:
  """Resolves the CLI `--target` option to a single export_hf target string."""
  if not target:
    return _DEFAULT_TARGET
  if isinstance(target, str):
    return target.strip() or _DEFAULT_TARGET
  cleaned = [t.strip() for t in target if t and t.strip()]
  if not cleaned:
    return _DEFAULT_TARGET
  if len(cleaned) > 1:
    raise click.UsageError(
        "Hugging Face conversion supports a single --target (e.g. --target"
        " cpu_gpu)."
    )
  return cleaned[0]


def convert_huggingface(
    model: str,
    output: str,
    target: tuple[str, ...] | str | None = (),
    export_aipack: pathlib.Path | None = None,
    quantize: str | None = None,
    prefill_lengths: str | None = None,
    cache_length: int | None = None,
    bundle_litert_lm: bool | None = None,
    llm_metadata: str = litert_lm_config.AUTO,
    task: str = "auto",
    dry_run: bool = False,
) -> Any:
  """Converts models using HuggingFace Automated Export (export_hf).

  Args:
    model: The Hugging Face model ID (e.g., Qwen/Qwen3-0.6B).
    output: The directory to save the converted model.
    target: Hardware target preset (default: 'cpu_gpu').
    export_aipack: Unused for Hugging Face models.
    quantize: Quantization recipe to apply.
    prefill_lengths: Comma-separated list of prefill lengths.
    cache_length: KV cache length.
    bundle_litert_lm: Whether to bundle artifacts into a .litert_lm package.
    llm_metadata: LlmMetadata for the .litertlm bundle: 'auto' uses the
      canonical LiteRT-LM config of the detected model family, 'none' keeps the
      metadata generated by export_hf, anything else is a path to a pbtext.
    task: Export task ('auto' to detect from the checkpoint).
    dry_run: If True, only resolves and prints the export plan.

  Returns:
    The resolved `ExportPlan`.
  """
  del export_aipack
  hf_export = _export_hf()
  click.echo(f"Starting conversion for model '{model}'")

  metadata_tmp_dir = tempfile.TemporaryDirectory(prefix="litert_cli_metadata_")
  try:
    hf_target = _resolve_target(target)
    export_kwargs: dict[str, Any] = {}
    if quantize is not None:
      export_kwargs["quantization_recipe"] = (
          None if quantize.strip().lower() == "none" else quantize
      )
    if prefill_lengths is not None:
      export_kwargs["prefill_lengths"] = [
          int(x.strip()) for x in prefill_lengths.split(",")
      ]
    if cache_length is not None:
      export_kwargs["cache_length"] = cache_length
    if bundle_litert_lm is not None:
      export_kwargs["bundle_litert_lm"] = bundle_litert_lm
    if llm_metadata == litert_lm_config.NONE:
      export_kwargs["litert_lm_llm_metadata_override"] = None
      export_kwargs["use_jinja_template"] = False
    elif llm_metadata != litert_lm_config.AUTO:
      path = pathlib.Path(llm_metadata)
      if not path.is_file():
        raise click.BadParameter(
            f"LlmMetadata pbtext not found: {llm_metadata}",
            param_hint="--llm-metadata",
        )
      click.echo(f"Using LlmMetadata from {path}")
      export_kwargs["litert_lm_llm_metadata_override"] = str(path)
      export_kwargs["use_jinja_template"] = True

    try:
      plan = hf_export.export(
          model=model,
          output_dir=output,
          task=task,
          target=hf_target,
          dry_run=True,
          **export_kwargs,
      )
    except (ValueError, NotImplementedError) as e:
      raise click.UsageError(str(e)) from e

    if dry_run:
      click.echo(plan)
      return plan

    resolved_bundle = plan.export_kwargs.get("bundle_litert_lm", True)
    if (
        llm_metadata == litert_lm_config.AUTO
        and resolved_bundle
        and plan.task == "text_generation"
        and "litert_lm_llm_metadata_override" not in plan.export_kwargs
    ):
      max_num_tokens = int(
          cache_length
          or plan.export_kwargs.get("llm_metadata_max_num_tokens_override")
          or plan.export_kwargs.get("cache_length", 4096)
      )
      metadata_path = _resolve_llm_metadata(
          llm_metadata,
          model,
          plan.model_type,
          max_num_tokens,
          metadata_tmp_dir.name,
      )
      if metadata_path:
        export_kwargs["litert_lm_llm_metadata_override"] = metadata_path
        export_kwargs["use_jinja_template"] = True

    plan = hf_export.export(
        model=model,
        output_dir=output,
        task=task,
        target=hf_target,
        trust_remote_code=False,
        **export_kwargs,
    )
    click.echo(f"Successfully converted and saved model to {output}")
    return plan

  except Exception as e:
    if isinstance(e, ModuleNotFoundError):
      message = _missing_dependency_message(model, e)
      if message is not None:
        raise click.ClickException(message) from e
    click.echo(f"Error during conversion: {e}")
    # Re-raise to let click handle the error exit
    raise
  finally:
    metadata_tmp_dir.cleanup()


# pip packages of modules that export_hf model extensions import lazily, where
# the package name differs from the module name.
_PIP_PACKAGES = {"nemo": "nemo_toolkit[asr]"}


def _missing_dependency_message(
    model: str, error: ModuleNotFoundError
) -> str | None:
  """Returns an actionable message for a missing model-specific package."""
  name = (error.name or "").split(".")[0]
  if not name:
    return None
  package = _PIP_PACKAGES.get(name, name)
  return (
      f"Converting '{model}' needs the Python package '{package}', which is"
      f' not installed. Install it (e.g. `pip install "{package}"`) and'
      f" retry.\n({error})"
  )


def _resolve_llm_metadata(
    llm_metadata: str,
    model: str,
    config,
    cache_length: int,
    tmp_dir: str,
) -> str | None:
  """Returns the LlmMetadata override path for export_hf, or None."""
  if llm_metadata == litert_lm_config.NONE:
    return None
  if llm_metadata != litert_lm_config.AUTO:
    path = pathlib.Path(llm_metadata)
    if not path.is_file():
      raise click.BadParameter(
          f"LlmMetadata pbtext not found: {llm_metadata}",
          param_hint="--llm-metadata",
      )
    click.echo(f"Using LlmMetadata from {path}")
    return str(path)

  family = litert_lm_config.detect_family(model, config)
  if family is None:
    click.echo(
        "No canonical LiteRT-LM config for this model; using the metadata"
        " generated by export_hf."
    )
    return None
  try:
    path = litert_lm_config.write_metadata_override(
        family, cache_length, tmp_dir
    )
  except RuntimeError as e:
    click.echo(
        f"Warning: {e}. Falling back to the metadata generated by export_hf"
        " (no chat template, thinking or tool calls).",
        err=True,
    )
    return None
  click.echo(f"Using the canonical LiteRT-LM config for '{family}'.")
  return path
