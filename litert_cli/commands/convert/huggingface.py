"""Hugging Face model conversion for `litert convert <hf_id>`.

All model-specific knowledge lives in litert-torch: `auto_export` detects the
task from the checkpoint and applies the export settings that each
architecture's `ModelExtension` recommends. This module only:

1. maps the CLI's high-level options onto `auto_export`,
2. adds the canonical LiteRT-LM metadata / chat template that the extension
   names (fetched from the LiteRT-LM repository),
3. prints the resolved plan, runs the export and the optional AOT compilation,
   and prints how to run the result.
"""

from __future__ import annotations

from collections.abc import Mapping
import pathlib
import shutil
import tempfile
from typing import Any

import click
from litert_cli.commands.convert import hf_options
from litert_cli.commands.convert import litert_lm_config
from litert_cli.core import npu_utils

# litert-torch `auto_export` preset applied by the CLI.
_PRESET = "recommended"


def _auto_export():
  """Imports litert-torch lazily, so `litert --help` does not load torch."""
  # pylint: disable=g-import-not-at-top
  from litert_torch.generative.export_hf import auto_export

  return auto_export


def convert_huggingface(
    model: str,
    output: str,
    target: tuple[str, ...],
    export_aipack: pathlib.Path | None,
    quantize: str | None = None,
    prefill_lengths: str | None = None,
    cache_length: int | None = None,
    bundle_litert_lm: bool | None = None,
    llm_metadata: str = litert_lm_config.AUTO,
    task: str | None = None,
    gpu_optimizations: bool | None = None,
    externalize_weights: bool | None = None,
    extension_modules: str | None = None,
    export_args: tuple[str, ...] = (),
    dry_run: bool = False,
) -> Any:
  """Converts a Hugging Face checkpoint with litert-torch `auto_export`.

  Every option left as `None` uses litert-torch's recommended value for the
  detected architecture.

  Args:
    model: Hugging Face model ID (e.g. Qwen/Qwen3-0.6B) or local checkpoint.
    output: Directory to save the converted model to.
    target: NPU targets to AOT compile for.
    export_aipack: Output directory for an AI Pack (PODAI).
    quantize: Quantization recipe ('none' for float).
    prefill_lengths: Comma-separated prefill lengths.
    cache_length: KV cache length.
    bundle_litert_lm: Whether to bundle a `.litertlm` package.
    llm_metadata: 'auto' (canonical LiteRT-LM config named by litert-torch),
      'none' (metadata generated by export_hf) or a path to a pbtext.
    task: Export task or alias; `None` / 'auto' detects it.
    gpu_optimizations: Whether to emit GPU composites (`apply_gpu_composites`).
    externalize_weights: Whether to externalize weights in the `.litertlm`.
    extension_modules: Comma-separated out-of-tree `ModelExtension` modules.
    export_args: Extra `KEY=VALUE` export_hf arguments.
    dry_run: Only print the resolved plan.

  Returns:
    The litert-torch `AutoExportPlan` that was resolved.

  Raises:
    click.ClickException: If an option is invalid or the export fails.
  """
  click.echo(f"Starting conversion for model '{model}'")
  try:
    overrides = hf_options.build_overrides(
        quantize=quantize,
        prefill_lengths=prefill_lengths,
        cache_length=cache_length,
        bundle_litert_lm=bundle_litert_lm,
        gpu_optimizations=gpu_optimizations,
        externalize_weights=externalize_weights,
        export_args=hf_options.parse_export_args(export_args),
    )
    export_task = hf_options.normalize_task(task)
  except ValueError as e:
    raise click.UsageError(str(e)) from e

  auto_export = _auto_export()
  try:
    plan = auto_export.resolve(
        model,
        task=export_task,
        preset=_PRESET,
        extension_modules=extension_modules,
        **overrides,
    )
  except ValueError as e:
    raise click.UsageError(str(e)) from e

  with tempfile.TemporaryDirectory(prefix="litert_cli_metadata_") as tmp_dir:
    litert_lm_kwargs = _litert_lm_kwargs(
        plan, model, llm_metadata, overrides, tmp_dir, fetch=not dry_run
    )
    _print_plan(plan, litert_lm_kwargs)
    if dry_run:
      click.echo("Dry run: nothing exported.")
      return plan

    plan = auto_export.export(
        model,
        output,
        task=export_task,
        preset=_PRESET,
        extension_modules=extension_modules,
        **overrides,
        **litert_lm_kwargs,
    )

  output_dir = pathlib.Path(output)
  if target:
    _aot_compile(output_dir, target, export_aipack)
  click.echo(f"Successfully converted and saved model to {output}")
  _print_next_steps(plan, output_dir)
  return plan


def _litert_lm_kwargs(
    plan: Any,
    model: str,
    llm_metadata: str,
    overrides: Mapping[str, Any],
    tmp_dir: str,
    fetch: bool,
) -> dict[str, Any]:
  """Returns export_hf arguments for the canonical LiteRT-LM config files.

  Args:
    plan: The resolved `AutoExportPlan`.
    model: Hugging Face model ID or local checkpoint.
    llm_metadata: The `--llm-metadata` value.
    overrides: Arguments set on the command line (they take precedence).
    tmp_dir: Directory to write the fetched files to.
    fetch: Whether to fetch the files (False for a dry run).

  Returns:
    Arguments such as `litert_lm_llm_metadata_override`,
    `jinja_chat_template_override` and `use_jinja_template`.
  """
  if (
      plan.task not in hf_options.LLM_TASKS
      or plan.export_kwargs.get("bundle_litert_lm") is False
  ):
    return {}
  kwargs = {}
  if (
      plan.task == "text_generation"
      and "litert_lm_llm_metadata_override" not in overrides
  ):
    metadata = _llm_metadata_path(plan, model, llm_metadata, tmp_dir, fetch)
    if metadata:
      kwargs["litert_lm_llm_metadata_override"] = metadata
  if (
      plan.litert_lm_chat_template
      and "jinja_chat_template_override" not in overrides
  ):
    family, filename = plan.litert_lm_chat_template.split("/", 1)
    if fetch:
      try:
        kwargs["jinja_chat_template_override"] = (
            litert_lm_config.write_canonical_file(family, filename, tmp_dir)
        )
      except RuntimeError as e:
        click.echo(f"Warning: {e}. Using the checkpoint template.", err=True)
    else:
      kwargs["jinja_chat_template_override"] = (
          f"LiteRT-LM models/{plan.litert_lm_chat_template}"
      )
  if kwargs and "use_jinja_template" not in overrides:
    kwargs["use_jinja_template"] = True
  return kwargs


def _llm_metadata_path(
    plan: Any, model: str, llm_metadata: str, tmp_dir: str, fetch: bool
) -> str | None:
  """Returns the LlmMetadata override for `--llm-metadata`, or None."""
  if llm_metadata == litert_lm_config.NONE:
    return None
  if llm_metadata != litert_lm_config.AUTO:
    path = pathlib.Path(llm_metadata)
    if not path.is_file():
      raise click.BadParameter(
          f"LlmMetadata pbtext not found: {llm_metadata}",
          param_hint="--llm-metadata",
      )
    return str(path)
  # The family comes from litert-torch; `detect_family` covers checkpoints
  # without a litert-torch extension (e.g. Qwen2.5, MiniCPM5).
  family = plan.litert_lm_model_family or litert_lm_config.detect_family(
      model, _ConfigView(plan.model_type)
  )
  if family is None:
    return None
  if not fetch:
    return f"LiteRT-LM models/{family}/LlmMetadataProto.pbtext"
  cache_length = plan.export_kwargs.get("cache_length", 4096)
  try:
    return litert_lm_config.write_metadata_override(
        family, cache_length, tmp_dir
    )
  except RuntimeError as e:
    click.echo(
        f"Warning: {e}. Using the metadata generated by export_hf (no chat"
        " template, thinking or tool calls).",
        err=True,
    )
    return None


class _ConfigView:
  """Minimal config object for `litert_lm_config.detect_family`."""

  def __init__(self, model_type: str | None):
    self.model_type = model_type
    self.text_config = None


def _print_plan(plan: Any, litert_lm_kwargs: Mapping[str, Any]) -> None:
  """Prints the resolved settings and where each one came from."""
  rows = list(plan.summary_rows())
  rows += [(k, str(v), "litert-lm") for k, v in litert_lm_kwargs.items()]
  width = max(len(name) for name, _, _ in rows)
  click.echo("Export plan:")
  for name, value, source in rows:
    click.echo(f"  {name:<{width}}  {value}  [{source}]")


def _print_next_steps(plan: Any, output_dir: pathlib.Path) -> None:
  """Prints how to run the exported model."""
  bundles = sorted(output_dir.glob("*.litertlm"))
  if not bundles:
    click.echo(
        f"litert-torch does not package '{plan.task}' models into a .litertlm"
        f" yet; the exported .tflite files are in {output_dir}."
    )
    return
  bundle = bundles[0]
  click.echo("Next steps:")
  if plan.task in hf_options.LLM_TASKS:
    click.echo(f'  litert lm run {bundle} --prompt="Hello"')
    return
  model_name = (
      f" --model_name={plan.runtime_model_name}"
      if plan.runtime_model_name
      else ""
  )
  click.echo(
      f"  omni_runner --model_path={bundle}{model_name} (LiteRT-LM"
      " //omni:omni_runner)"
  )


def _aot_compile(
    output_dir: pathlib.Path,
    target: tuple[str, ...],
    export_aipack: pathlib.Path | None,
) -> None:
  """AOT compiles the exported .tflite for NPU targets."""
  # pylint: disable=g-import-not-at-top
  from ai_edge_litert.aot import aot_compile as aot_lib
  from ai_edge_litert.aot.ai_pack import export_lib as ai_pack_export

  tflite_files = sorted(output_dir.glob("*.tflite"))
  if not tflite_files:
    raise FileNotFoundError(
        f"No .tflite files found in HF export output: {output_dir}"
    )
  target_tflite = tflite_files[0]
  base_name = target_tflite.stem

  click.echo(
      f"Compiling converted model {target_tflite} for targets:"
      f" {', '.join(target)}"
  )
  aot_targets = [npu_utils.get_target(t) for t in target]
  compiled_models = aot_lib.aot_compile(
      str(target_tflite),
      target=aot_targets,
      keep_going=False,
  )

  if export_aipack:
    export_dir = pathlib.Path(export_aipack)
    click.echo(f"Exporting AI Pack to: {export_dir}")
    shutil.rmtree(export_dir, ignore_errors=True)
    export_dir.mkdir(parents=True, exist_ok=True)
    ai_pack_export.export(compiled_models, str(export_dir), base_name, "model")
  else:
    click.echo(f"Exporting compiled model over original in {output_dir}")
    compiled_models.export(str(output_dir), model_name=base_name)
